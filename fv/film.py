NEGATIVE = ("subtitles, watermark, caption, blurry, low quality, flicker, deformed hands, distorted faces, "
            "extra limbs, letterbox, black bars, widescreen bars, frame border, picture in picture, "
            "split screen, collage, cartoon, CGI look, plastic skin")
MOTION = " Modern digital cinema footage; the picture fills the whole frame, edge to edge."

PROMPT = """You are the director of a {kind}. The brief:
"{script}"

Plan it as about {n} shots that together last about {seconds} seconds and tell it from start to finish with a clear beginning, middle and end. If the brief has dialogue, keep every line of it, in order, and use as many shots as the lines need. {style}
Every shot is generated by a text-to-video model that knows nothing about the other shots, so:
- "cast": every recurring person, animal or product, each with a fixed name and a visual description of 20 to 40 words (age, build, face, hair, exact clothes and colours; for a product: shape, material, colours, label). All invented, no real people or celebrities.
- "look": one line about the whole film's photography: lens feel, colour palette, contrast, lighting style. Don't name film stocks, film formats or cameras.
- "shots": for each shot, "seconds" (2 to 8, long enough to say its lines), "cast" (the names in it, may be empty), "dialogue" (the words spoken in this shot: a list of {{"who": a cast name, "line": the exact words}}, at most 2 short lines, said by people in frame, usually one speaker per shot; an empty list when nobody speaks, as in a reaction shot) and "video": 2 to 4 sentences in the present tense about the picture only: the shot size and angle, who or what is in frame and exactly what they do from the start to the end of the shot, the setting, the light, and how the camera moves. Put no dialogue or quotes in "video". Use the cast names; never describe them again. Real-world physics, believable motion, one continuous action per shot. No on-screen text, titles or captions{talk}.
Answer with only a JSON object with the keys "title" (2 to 5 words), "cast", "look" and "shots"."""

ONE_PROMPT = """You are the director of a {kind} filmed as ONE single continuous shot: no cuts, no edits, the camera keeps rolling from the first frame to the last. The brief:
"{script}"

It lasts about {seconds} seconds and tells the whole brief in that one take, with a clear beginning, middle and end. {style}
The shot is generated by a text-to-video model, so:
- "cast": every person, animal or product in it, each with a fixed name and a visual description of 20 to 40 words (age, build, face, hair, exact clothes and colours; for a product: shape, material, colours, label). All invented, no real people or celebrities.
- "look": one line about the photography: lens feel, colour palette, contrast, lighting style. Don't name film stocks, film formats or cameras.
- "dialogue": every line spoken in the take, in order: a list of {{"who": a cast name, "line": the exact words}}. Keep the brief's own lines word for word. At most {words} words in all, so they fit the time; an empty list when nobody speaks.
- "video": 4 to 7 sentences in the present tense about the picture only: how the shot opens (shot size, angle, who is in frame), how the camera moves through the scene (a slow push in, a dolly, a pan, a follow) and what everyone does from the start to the end, in order, the setting and the light. One place, one continuous action, no cuts. Put no dialogue or quotes in "video". Use the cast names; never describe them again. Real-world physics, believable motion. No on-screen text, titles or captions{talk}.
Answer with only a JSON object with the keys "title" (2 to 5 words), "cast", "look", "dialogue" and "video"."""

# the longest single take each engine makes well (MiniMax H3: 4 to 15 s; LTX-2.5: about 20 s)
ONE_SHOT_MAX = {"h3": 15.0}
ONE_SHOT_MAX_LTX = 20.0


def one_shot_max(preset: str) -> float:
    return ONE_SHOT_MAX.get(formats.engine_of(preset), ONE_SHOT_MAX_LTX)


# a screenplay's dialogue is taken from the script word for word; Gemma only gives each group of
# lines its picture (it drops, merges and reorders lines when it rewrites them itself)
DIALOGUE = """
The scene's dialogue is already split into numbered groups; every group is one shot, in this order:
{groups}
Write one shot for every group, in order, with "lines": [its group number]. You may add shots where nobody speaks (an opening, a reaction, an ending) between them, with "lines": []. In these shots, "dialogue" is not needed: write the picture in "video", with the speaker in frame."""

_SPEAKER = re.compile(r"^\s*([A-Z][A-Z0-9 .'\-]{0,30}[A-Z0-9])(?:\s*\([^)]*\))?\s*:\s*(.+?)\s*$")


def script_lines(script: str) -> list[dict]:
    """[{who, line}] from a screenplay's NAME: "line" lines, in order ([] when it has fewer than 2)."""
    out = []
    for ln in script.splitlines():
        m = _SPEAKER.match(ln)
        if m and not re.match(r"(INT|EXT|INT/EXT|CUT TO|FADE|SMASH CUT)\b", m.group(1)):
            out.append({"who": m.group(1).title(), "line": m.group(2).strip().strip('"\u201c\u201d').strip()})
    return out if len(out) >= 2 else []


def group_lines(lines: list[dict]) -> list[list[dict]]:
    """One shot per line, or two short ones together (at most 12 words)."""
    groups = []
    for x in lines:
        g = groups[-1] if groups else None
        if g and len(g) == 1 and len(g[0]["line"].split()) + len(x["line"].split()) <= 12:
            g.append(x)
        else:
            groups.append([x])
    return groups


def films_dir(out_root: str) -> str:
    return os.path.join(out_root, "oneshot-mv", "films")


def _slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:40] or "film"


def _decode(path: str) -> tuple[np.ndarray, int]:
    from .assemble import ffmpeg_exe
    sr = 44100
    raw = subprocess.run([ffmpeg_exe(), "-v", "error", "-nostdin", "-i", path, "-f", "f32le", "-ac", "2", "-ar", str(sr), "-"],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.float32).reshape(-1, 2).T.copy(), sr


def write_shots(script: str, seconds: float, kind: str = "film", style: str = "", seed: int = 1, log=print,
                one_shot: bool = False) -> dict:
    """{title, cast: [{name, look}], look, shots: [{seconds, cast, video}]} from Gemma."""
    from . import theme
    if one_shot:
        return _write_one(script, seconds, kind, style, seed, log)
    n = max(2, int(round(seconds / (3.2 if kind == "commercial" else 4.5))))
    groups = group_lines(script_lines(script))
    if groups:
        n = len(groups) + 1
        seconds = max(seconds, sum(talk_seconds(g) for g in groups))
    want = PROMPT.format(kind={"commercial": "TV commercial", "film": "short film"}.get(kind, kind), script=script.strip(),
                         n=n, seconds=int(round(seconds)), style=f"Style: {style.strip()}." if style.strip() else "",
                         talk=", nobody talks to the camera" if kind != "film" else "")
    if groups:
        want += DIALOGUE.format(groups="\n".join(f"{i + 1}. " + " / ".join(f'{x["who"].upper()}: "{x["line"]}"' for x in g)
                                                 for i, g in enumerate(groups)))
    for attempt in range(3):
        d = theme._parse(theme.llm(want, seed=seed + attempt, max_length=2600, log=log) or "")
        shots = (d or {}).get("shots") or []
        if len(shots) >= 2 and all(isinstance(s, dict) and str(s.get("video", "")).strip() for s in shots):
            break
        log(f"[OneShotMV] film: the shot list didn't parse (try {attempt + 1})")
        d = None
    if not d:
        raise RuntimeError("Gemma couldn't write a shot list for this brief: try a longer or plainer script.")
    cast = _cast(d)
    shots = [{"seconds": float(s.get("seconds") or 4), "cast": [str(x) for x in (s.get("cast") or []) if x],
              "dialogue": _lines(s.get("dialogue")), "video": str(s["video"]).strip(), "talks": bool(s.get("lines") or s.get("dialogue"))}
             for s in d["shots"]]
    if groups:
        shots = _place_lines(shots, groups, cast)
    for s in shots:
        s.pop("talks", None)
    return {"title": re.sub(r"[^\w' &-]+", "", str(d.get("title") or "Untitled")).strip()[:60] or "Untitled",
            "cast": cast, "look": str(d.get("look") or "").strip(), "raw": d, "shots": shots}


def _cast(d: dict) -> list[dict]:
    """[{name, look}] from what Gemma wrote (a list of objects, a {name: description} dict, "Name: description" strings)."""
    cast = []
    raw = d.get("cast") or []
    if isinstance(raw, dict):  # {"Silas": "a man in his seventies..."} or {"Silas": {...}}
        raw = [{"name": k, **(v if isinstance(v, dict) else {"look": v})} for k, v in raw.items()]
    for c in raw if isinstance(raw, list) else []:
        if isinstance(c, str) and ":" in c:  # "Silas: a man in his seventies..."
            c = dict(zip(("name", "look"), (x.strip() for x in c.split(":", 1))))
        if not isinstance(c, dict):
            continue
        name = str(c.get("name") or "").strip()
        if not name:
            continue
        desc = c.get("look") or c.get("description") or c.get("visual") or c.get("desc") or \
            next((v for k, v in c.items() if k != "name" and isinstance(v, str) and len(v) > 20), "")
        cast.append({"name": name, "look": str(desc).strip()})
    return cast


def _write_one(script: str, seconds: float, kind: str, style: str, seed: int, log=print) -> dict:
    """The one-shot film: one continuous take with every line in it (a screenplay's lines word for word)."""
    from . import theme
    lines = script_lines(script)
    words = max(4, int((seconds - 1.2) * 2.6))
    want = ONE_PROMPT.format(kind={"commercial": "TV commercial", "film": "short film"}.get(kind, kind), script=script.strip(),
                             seconds=int(round(seconds)), words=words, style=f"Style: {style.strip()}." if style.strip() else "",
                             talk=", nobody talks to the camera" if kind != "film" else "")
    d = None
    for attempt in range(3):
        d = theme._parse(theme.llm(want, seed=seed + attempt, max_length=2000, log=log) or "")
        if d and str(d.get("video", "")).strip():
            break
        log(f"[OneShotMV] film: the one-shot plan didn't parse (try {attempt + 1})")
        d = None
    if not d:
        raise RuntimeError("Gemma couldn't plan this one-shot: try a shorter or plainer brief.")
    cast = _cast(d)

    def name(who):
        w = who.lower()
        return next((c["name"] for c in cast if w == c["name"].lower() or w in c["name"].lower().split()), who)
    dialogue = [{"who": name(x["who"]), "line": x["line"]} for x in lines] if lines else _lines(d.get("dialogue"))
    video = str(d["video"]).strip()
    who = [c["name"] for c in cast if c["name"].lower() in video.lower()]
    shot = {"seconds": seconds, "cast": list(dict.fromkeys(who + [x["who"] for x in dialogue if x["who"]])),
            "dialogue": dialogue, "video": video}
    return {"title": re.sub(r"[^\w' &-]+", "", str(d.get("title") or "Untitled")).strip()[:60] or "Untitled",
            "cast": cast, "look": str(d.get("look") or "").strip(), "raw": d, "shots": [shot]}


def _place_lines(shots: list[dict], groups: list[list[dict]], cast: list[dict]) -> list[dict]:
    """The script's line groups in order on the shots Gemma marked as talking (whatever numbers it
    gave them); talking shots past the last group go silent, groups past the last talking shot get
    a shot of their own. Speakers take their cast names ("Jerry" -> "Jerry Seinfeld")."""
    def name(who):
        w = who.lower()
        return next((c["name"] for c in cast if w == c["name"].lower() or w in c["name"].lower().split()), who)
    k = 0
    for s in shots:
        if s["talks"] and k < len(groups):
            s["dialogue"] = [{"who": name(x["who"]), "line": x["line"]} for x in groups[k]]
            k += 1
        else:
            s["dialogue"] = []
    for g in groups[k:]:
        who = list(dict.fromkeys(name(x["who"]) for x in g))
        shots.append({"seconds": 3.0, "cast": who, "dialogue": [{"who": name(x["who"]), "line": x["line"]} for x in g],
                      "video": f"A medium shot of {' and '.join(who)} in the same place as the shot before, talking."})
    for s in shots:  # the speakers are in the shot
        s["cast"] = list(dict.fromkeys(s["cast"] + [x["who"] for x in s["dialogue"]]))
    return shots


def _lines(raw) -> list[dict]:
    """[{who, line}] from what Gemma wrote ({"who", "line"} items, "Name: words" strings)."""
    out = []
    for x in raw if isinstance(raw, list) else []:
        if isinstance(x, str) and ":" in x:
            x = dict(zip(("who", "line"), (t.strip() for t in x.split(":", 1))))
        if isinstance(x, dict) and str(x.get("line") or x.get("text") or "").strip():
            out.append({"who": str(x.get("who") or x.get("speaker") or "").strip(),
                        "line": str(x.get("line") or x.get("text")).strip().strip('"\u201c\u201d')})
    return out


def talk_seconds(lines: list[dict]) -> float:
    """How long a shot needs to say its lines: about 2.6 words a second, a beat between lines and
    one before the cut."""
    if not lines:
        return 0.0
    words = sum(len(x["line"].split()) for x in lines)
    return words / 2.6 + 0.4 * len(lines) + 0.8


# film formats and stocks in a text-to-video prompt bring the film itself into the picture: a
# rounded gate, sprocket holes, a frame border (LTX-2.5 at cfg 1 has no negative prompt to stop it)
_FILMIC = re.compile(r"\b(?:(?:shot|captured|filmed) on )?(?:(?:super ?8|8 ?mm|16 ?mm|35 ?mm|65 ?mm|70 ?mm|imax)(?: film)?(?: stock)?|"
                     r"kodak(?: \w+)?(?: \d{2,4}\w?)?|fuji(?:film)?(?: \w+)?(?: \d{2,4})?|portra(?: \d+)?|"
                     r"cinestill(?: \d+\w?)?|ektachrome|film stock|film grain|celluloid)\b", re.I)


def defilm(text: str) -> str:
    """A look without film stocks or formats ("35mm film stock, Kodak Portra 400" -> a film look)."""
    t = _FILMIC.sub("", text or "")
    t = re.sub(r"\s*,\s*(,\s*)+", ", ", t)
    t = re.sub(r"^[\s,;:]+|[\s,;]+$", "", re.sub(r"\s{2,}", " ", t)).strip()
    return re.sub(r"\s+([,.;])", r"\1", t)


def prompt_for(film: dict, shot: dict) -> str:
    """A shot's whole prompt: its action with every named cast member described in full (the model
    sees one shot at a time), then the film's look."""
    text = shot["video"]
    lines = shot.get("dialogue") or []
    who = [c for c in film.get("cast", []) if c["name"] in shot.get("cast", []) or c["name"].lower() in text.lower()]
    if who:
        lc = lambda t: t[0].lower() + t[1:] if re.match(r"(A|An|The)\b", t) else t  # "Silas is an 82-year-old man"
        text += " " + " ".join(f"{c['name']} is {lc(c['look'].rstrip('.'))}." for c in who if c["look"])
    if lines:  # the exact words, then silence: a clip longer than its lines fills itself with made-up talk
        if not re.search(r'["\u201c]', text):  # (a film planned earlier has them quoted in its description)
            text += " " + " ".join(f'{x["who"] or "They"} says: "{x["line"]}"' for x in lines)
        text += " Nobody says anything else."
    else:
        text += " Nobody speaks."
    look, style = defilm(film.get("look", "")), defilm(film.get("style", ""))
    if look:
        text += f" Look: {look.rstrip('.')}."
    if style:
        text += f" Style: {style.rstrip('.')}."
    text = defilm(text) if _FILMIC.search(text) else text
    return text + MOTION


def _timing(shots: list[dict], seconds: float, beats: list[float] | None, cap: float = 10.0) -> list[tuple[float, float]]:
    """(t0, t1) per shot. Without music each shot keeps the length it needs (its lines said in
    full) and the film is as long as they add up to; with music the lengths are scaled to the
    film's and every cut moves onto the nearest beat (a shot keeps at least 1.2 s)."""
    raw = [min(cap, max(1.5, float(s["seconds"]), talk_seconds(s.get("dialogue")))) for s in shots]
    if not beats:
        edges = [0.0]
        for r in raw:
            edges.append(edges[-1] + r)
        return [(round(edges[i], 3), round(edges[i + 1], 3)) for i in range(len(shots))]
    k = seconds / sum(raw)
    cuts, t = [], 0.0
    for r in raw[:-1]:
        t += r * k
        cuts.append(t)
    if beats:
        b = np.array([x for x in beats if 0.8 < x < seconds - 0.8])
        snapped, last = [], 0.0
        for c in cuts:
            if len(b):
                cand = b[(b > last + 1.2)]
                c = float(cand[np.argmin(np.abs(cand - c))]) if len(cand) else c
            snapped.append(c)
            last = c
        cuts = snapped
    edges = [0.0] + cuts + [seconds]
    return [(round(edges[i], 3), round(edges[i + 1], 3)) for i in range(len(shots))]


def _beats(song_path: str, start: float, seconds: float) -> tuple[list[float], float, float]:
    """The song's beat times inside the film's window (from 0), the window's start and the tempo."""
    from . import beat
    x, sr = _decode(song_path)
    tl = beat.analyze(x, sr)
    dur = x.shape[1] / sr
    if start < 0:  # the strongest stretch, as the music video picks it
        try:
            start = float(beat.choose_window(tl, seconds)[0])
        except Exception:
            start = 0.0
    start = max(0.0, min(start, max(0.0, dur - seconds)))
    bts = [float(b) - start for b in tl.get("beats", []) if start <= float(b) <= start + seconds]
    return bts, start, float(tl.get("tempo") or 0)


def shot_job(film: dict, i: int, seed: int, take: int = 0) -> dict:
    """One shot's text-to-video graph (a re-shoot: a new seed and a _t<take> name)."""
    s = film["shots"][i]
    fps = formats.PRESETS[film["preset"]]["fps"]
    want = (s.get("planned") or s["t1"] - s["t0"]) + (0.6 if s.get("dialogue") else 0.2)
    frames = formats.ltx_frames(min(want, one_shot_max(film["preset"])) if film.get("one_shot") else want, fps)
    name = f"s{i:03d}" + (f"_t{take}" if take else "")
    s["prompt"] = prompt_for(film, s)  # a re-shoot gets today's prompt rules (a film planned earlier: its quoted lines)
    g = graphs.ltx_render(vsr=bool(film.get("h3_vsr")), preset=film["preset"], fmt=film["format"], key_path=None,
                          prompt=s["prompt"], negative=NEGATIVE, frames=frames, seed=seed, prefix=f"{film['rel']}/{name}",
                          size=formats.render_size(film["format"], film["preset"]), sound=True)
    return g.nodes


def plan(*, script: str, seconds: float, fmt: str, preset: str, seed: int, out_root: str, kind: str = "film",
         style: str = "", song_path: str = "", song_start: float = -1.0, look: str = "none", run_name: str = "",
         h3_upscale: str = "auto", sound: bool = True, one_shot: bool = False, log=print) -> dict:
    """Write the shot list and save film.json; returns the film (its jobs under "jobs")."""
    t = time.time()
    seconds = float(max(5.0, min(300.0, seconds)))
    note = ""
    if one_shot:
        cap = one_shot_max(preset)
        need = talk_seconds(script_lines(script))
        if seconds > cap:
            note = f"one shot: {cap:.0f} s at most on this model"
        if need > cap:
            note = f"one shot: the lines need about {need:.0f} s, more than the {cap:.0f} s one take holds; they may be rushed or cut"
        seconds = min(cap, max(seconds if seconds <= cap else cap, need))
    spec = write_shots(script, seconds, kind, style, seed, log, one_shot=one_shot)
    name = run_name or f"{_slug(spec['title'])}-{time.strftime('%Y%m%d-%H%M')}"
    d = os.path.join(films_dir(out_root), name)
    os.makedirs(d, exist_ok=True)
    film = {"version": 1, "kind": kind, "script": script, "style": style, "seconds": seconds, "format": fmt,
            "preset": preset, "seed": seed, "look_grade": look, "sound": bool(sound), "run": name, "dir": d,
            "rel": os.path.relpath(d, out_root).replace(os.sep, "/"), "title": spec["title"], "cast": spec["cast"],
            "look": spec["look"], "llm": spec.get("raw"), "song": song_path, "song_start": 0.0, "tempo": 0.0,
            "one_shot": bool(one_shot), "note": note,
            "h3_vsr": formats.engine_of(preset) == "h3" and h3_upscale == "relayvsr" and graphs.relayvsr_ready(),
            "created": time.strftime("%Y-%m-%dT%H:%M")}
    beats = None
    if song_path:
        beats, film["song_start"], film["tempo"] = _beats(song_path, song_start, seconds)
    film["shots"] = spec["shots"]
    for s, (t0, t1) in zip(film["shots"], _timing(spec["shots"], seconds, beats, one_shot_max(preset) if one_shot else 10.0)):
        s["t0"], s["t1"] = t0, t1
        s["prompt"] = prompt_for(film, s)
    film["seconds"] = film["shots"][-1]["t1"]
    film["jobs"] = [{"name": f"s{i:03d}", "shot": i, "graph": shot_job(film, i, seed * 1000 + i)}
                    for i in range(len(film["shots"]))]
    save(film)
    if note:
        log(f"[OneShotMV] film: {note}")
    log(f"[OneShotMV] film: \"{film['title']}\", {len(film['shots'])} shots, {seconds:.0f} s, "
        f"{len(film['cast'])} in the cast ({time.time() - t:.0f} s)")
    return film


def save(film: dict) -> None:
    with open(os.path.join(film["dir"], "film.json"), "w", encoding="utf-8") as f:
        json.dump(film, f, indent=1)


def load(d: str) -> dict:
    with open(os.path.join(d, "film.json"), encoding="utf-8") as f:
        return json.load(f)


def cut_graph(d: str) -> dict:
    return {"1": {"class_type": "FVFilmCut", "inputs": {"film_dir": d}}}


def clip_for(d: str, i: int) -> str:
    """Shot i's newest take."""
    paths = glob.glob(os.path.join(d, f"s{i:03d}_*.mp4"))
    return max(paths, key=os.path.getmtime) if paths else ""


def _clip_audio(path: str, seconds: float, sr: int, start: float = 0.0) -> np.ndarray:
    from .assemble import ffmpeg_exe
    n = int(round(seconds * sr))
    try:
        raw = subprocess.run([ffmpeg_exe(), "-v", "error", "-nostdin", "-ss", f"{start:.4f}", "-i", path, "-t", f"{seconds:.4f}", "-f", "f32le",
                              "-ac", "2", "-ar", str(sr), "-"], capture_output=True, check=True).stdout
        a = np.frombuffer(raw, np.float32).reshape(-1, 2).T
    except Exception:
        a = np.zeros((2, 0), np.float32)
    out = np.zeros((2, n), np.float32)
    out[:, :min(n, a.shape[1])] = a[:, :n]
    fade = min(n // 2, int(0.02 * sr))  # no click at the cut
    if fade:
        ramp = np.linspace(0, 1, fade, dtype=np.float32)
        out[:, :fade] *= ramp
        out[:, n - fade:] *= ramp[::-1]
    return out


def _norm(w: str) -> str:
    return re.sub(r"[^a-z0-9]", "", w.lower())


def _speech(paths: list[str], log=print) -> dict:
    """{path: [(t0, t1, word)]}: what each take actually says (Whisper, the lyrics model)."""
    import whisper  # type: ignore
    from . import lyrics
    model = whisper.load_model(lyrics.MODEL, download_root=lyrics._model_dir())
    out = {}
    try:
        for p in paths:
            from .assemble import ffmpeg_exe
            raw = subprocess.run([ffmpeg_exe(), "-v", "error", "-nostdin", "-i", p, "-f", "f32le", "-ac", "1",
                                  "-ar", str(lyrics.SR), "-"], capture_output=True, check=True).stdout
            x = np.frombuffer(raw, np.float32).copy()
            r = model.transcribe(x, language="en", word_timestamps=True, condition_on_previous_text=False, verbose=None)
            out[p] = [(w["start"], w["end"], w["word"].strip()) for seg in r.get("segments", []) for w in seg.get("words", [])
                      if w.get("word", "").strip()]
    finally:
        del model
        import torch
        torch.cuda.empty_cache()
    return out


def _clip_seconds(path: str) -> float:
    import cv2
    cap = cv2.VideoCapture(path)
    n, fps = cap.get(cv2.CAP_PROP_FRAME_COUNT), cap.get(cv2.CAP_PROP_FPS) or 24.0
    cap.release()
    return n / fps


def fit_to_takes(film: dict, paths: list[str], log=print) -> None:
    """Without music: every shot runs to just after its last scripted word in the take as rendered
    (from just before its first one when the take talks before it) (a take says its lines at its own pace, and fills any time
    left with made-up talk), a silent shot runs its planned length; the shots follow each other.
    Sets each shot's "in" (seconds skipped at the take's start) and t0/t1."""
    for s in film["shots"]:  # films planned before "dialogue": the quoted lines in the shot's description
        if "dialogue" not in s:
            s["dialogue"] = [{"who": "", "line": q} for q in re.findall(r'["\u201c]([^"\u201d]{2,})["\u201d]', s.get("video", ""))]
    if film.get("one_shot"):  # one take, no edit: all of it
        p, s = paths[0], film["shots"][0]
        s["planned"] = s.get("planned") or (s["t1"] - s["t0"])
        s["in"], s["t0"], s["t1"] = 0.0, 0.0, round(_clip_seconds(p) if p else s["planned"], 3)
        film["seconds"] = s["t1"]
        return
    talk = [p for p, s in zip(paths, film["shots"]) if p and s.get("dialogue")]
    words = _speech(talk, log) if talk else {}
    t = 0.0
    for p, s in zip(paths, film["shots"]):
        planned = s.get("planned") or (s["t1"] - s["t0"])
        s["planned"] = planned
        length = min(planned, _clip_seconds(p)) if p else planned
        s["in"] = 0.0
        if p and s.get("dialogue") and words.get(p):
            ws = words[p]
            script = [_norm(w) for x in s["dialogue"] for w in x["line"].split() if _norm(w)]
            said = [_norm(w[2]) for w in ws]
            first, last, j = None, None, 0  # walk the script through the take: stop where its last word is first said
            for i, w in enumerate(said):
                k = next((k for k in range(j, min(j + 3, len(script))) if script[k] == w), None)
                if k is None:
                    continue
                first = i if first is None else first
                last, j = i, k + 1
                if j >= len(script):
                    break
            first = 0 if first is None else first
            last = len(said) - 1 if last is None or j < len(script) * 0.6 else last
            dur = _clip_seconds(p)
            s["in"] = round(max(0.0, ws[first][0] - 0.3), 3) if first > 0 else 0.0  # skip made-up talk, never the action
            end = min(dur, ws[last][1] + 0.5)
            length = max(1.0, end - s["in"])
        s["t0"], s["t1"] = round(t, 3), round(t + length, 3)
        t += length
    film["seconds"] = round(t, 3)


def cut(d: str, log=print) -> str:
    """final.mp4: every shot's newest take trimmed to its slot, the music or the shots' sound, the finish."""
    import torch
    from . import casting, stems
    from .assemble import ffmpeg_exe
    from .finish import STUDIO_DEFAULTS, Finisher, lab_stats
    film = load(d)
    fps = float(formats.PRESETS[film["preset"]]["fps"])
    dw, dh = formats.deliver_size(film["format"], int(film.get("resolution") or 1080))
    seconds = float(film["seconds"])
    shots = film["shots"]
    paths = [clip_for(d, i) for i in range(len(shots))]
    if not any(paths):
        raise RuntimeError("no shots rendered yet")
    if not (film.get("song") and os.path.isfile(film["song"])):
        fit_to_takes(film, paths, log)
        seconds = float(film["seconds"])
    dev = "cuda" if torch.cuda.is_available() else "cpu"

    def frames_of(path: str, n: int, start: float = 0.0):
        """n frames of a clip from its start, covering the delivery size (black when it's missing)."""
        if not path:
            for _ in range(n):
                yield np.zeros((dh, dw, 3), np.uint8)
            return
        p = subprocess.Popen([ffmpeg_exe(), "-v", "error", "-nostdin", "-ss", f"{start:.4f}", "-i", path, "-vf",
                              f"fps={fps},scale={dw}:{dh}:force_original_aspect_ratio=increase:flags=lanczos,crop={dw}:{dh}",
                              "-frames:v", str(n), "-f", "rawvideo", "-pix_fmt", "rgb24", "-"], stdout=subprocess.PIPE)
        last, k = None, 0
        while k < n:
            buf = p.stdout.read(dw * dh * 3)
            if len(buf) < dw * dh * 3:
                break
            last = np.frombuffer(buf, np.uint8).reshape(dh, dw, 3)
            k += 1
            yield last
        p.stdout.close()
        p.wait()
        for _ in range(n - k):  # a clip shorter than its slot holds its last frame
            yield last if last is not None else np.zeros((dh, dw, 3), np.uint8)

    # the finish: the house base and the Studio's grade, grain and vignette
    pk = casting.load_pack("crowd")
    cfg = dict(pk["finish"], **STUDIO_DEFAULTS)
    cfg.update({"look": film.get("look_grade") or "none", "grade_amount": 0.0}, **(film.get("finish_user") or {}))
    samples = []
    for p in paths:
        for f in frames_of(p, 1):
            samples.append(torch.from_numpy(f.copy()).to(dev).float() / 255)
    fin = Finisher(cfg, lab_stats(samples) if samples else None)

    # the sound: the music from its window, or every shot's own sound in its slot
    sr = 44100
    wav = os.path.join(d, "sound.wav")
    if film.get("song") and os.path.isfile(film["song"]):
        x, ssr = _decode(film["song"])
        a = x[:, int(film.get("song_start", 0) * ssr):int((film.get("song_start", 0) + seconds) * ssr)]
        n = int(seconds * ssr)
        if a.shape[1] < n:
            a = np.pad(a, ((0, 0), (0, n - a.shape[1])))
        fade = int(min(1.5, seconds / 6) * ssr)  # out, not cut off
        a[:, -fade:] *= np.linspace(1, 0, fade, dtype=np.float32)
        stems.write_wav(wav, a.astype(np.float32), ssr)
    elif film.get("sound", True):
        parts = [_clip_audio(p, s["t1"] - s["t0"], sr, s.get("in", 0.0)) if p else np.zeros((2, int((s["t1"] - s["t0"]) * sr)), np.float32)
                 for p, s in zip(paths, shots)]
        a = np.concatenate(parts, axis=1)
        peak = float(np.abs(a).max() or 1.0)  # up to -1 dBFS peak (the models' sound comes out quiet), at most +12 dB
        stems.write_wav(wav, (a * min(4.0, 0.89 / peak)).astype(np.float32), sr)
    else:
        stems.write_wav(wav, np.zeros((2, int(seconds * sr)), np.float32), sr)

    out = os.path.join(d, "final.mp4")
    tmp = out + ".part.mp4"
    enc = subprocess.Popen([ffmpeg_exe(), "-v", "error", "-y", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{dw}x{dh}",
                            "-r", str(fps), "-i", "-", "-i", wav, "-map", "0:v", "-map", "1:a", "-c:v", "libx264",
                            "-crf", "16", "-preset", "medium", "-tune", "grain", "-maxrate", "40M", "-bufsize", "60M",
                            "-pix_fmt", "yuv420p", "-movflags", "+faststart", "-c:a", "aac", "-b:a", "256k", "-shortest", tmp],
                           stdin=subprocess.PIPE)
    k = 0
    thumb = None
    for i, (p, s) in enumerate(zip(paths, shots)):
        n = int(round(s["t1"] * fps)) - int(round(s["t0"] * fps))
        for f in frames_of(p, n, s.get("in", 0.0)):
            x = torch.from_numpy(f.copy()).to(dev).float() / 255
            y = (fin(x, k).clamp(0, 1) * 255).round().byte().cpu().numpy()
            if thumb is None and k >= n // 2:
                thumb = y
            enc.stdin.write(y.tobytes())
            k += 1
    enc.stdin.close()
    enc.wait()
    if enc.returncode:
        raise RuntimeError("ffmpeg failed to write the cut")
    os.replace(tmp, out)
    if thumb is not None:
        import cv2
        cv2.imwrite(os.path.join(d, "thumb.jpg"), cv2.cvtColor(thumb, cv2.COLOR_RGB2BGR)[:, :, :],
                    [cv2.IMWRITE_JPEG_QUALITY, 88])
    film["final"] = out
    film["cut_at"] = time.strftime("%Y-%m-%dT%H:%M:%S")
    save(film)
    log(f"[OneShotMV] film: cut {film['title']} ({k} frames, {sum(1 for p in paths if p)}/{len(paths)} shots)")
    return out

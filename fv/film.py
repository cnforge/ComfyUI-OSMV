"""Film mode: a commercial, a short film or any piece without singers. A script (or one line) goes to
Gemma 3, which writes a cast, a look and a shot list; every shot is text to video (LTX-2.5 or
MiniMax H3, RelayVSR on H3 when asked); the cut joins the shots, lays the music (a song, cut on
its beats) or the shots' own sound, and applies the OneShot MV finish.

A film lives in output/oneshot-mv/films/<run>/: film.json (the brief, the cast, the shots and
their jobs), s000_*.mp4 ... (the shots; a re-shoot adds s000_t1_*.mp4, the newest is used) and
final.mp4. FVFilm plans and queues; FVFilmCut makes the cut and can run again (new look, new
takes) without rendering anything."""
from __future__ import annotations

import glob
import json
import math
import os
import re
import subprocess
import time

import numpy as np

from . import formats, graphs

NEGATIVE = ("subtitles, watermark, caption, blurry, low quality, flicker, deformed hands, distorted faces, "
            "extra limbs, letterbox, black bars, widescreen bars, frame border, picture in picture, "
            "split screen, collage, cartoon, CGI look, plastic skin")
MOTION = " Modern digital cinema footage; the picture fills the whole frame, edge to edge."

PROMPT = """You are the director of a {kind}. The brief:
"{script}"

Plan it as {n} shots that together last about {seconds} seconds and tell it from start to finish with a clear beginning, middle and end. {style}
Every shot is generated by a text-to-video model that knows nothing about the other shots, so:
- "cast": every recurring person, animal or product, each with a fixed name and a visual description of 20 to 40 words (age, build, face, hair, exact clothes and colours; for a product: shape, material, colours, label). All invented, no real people or celebrities.
- "look": one line about the whole film's photography: lens feel, colour palette, contrast, lighting style. Don't name film stocks, film formats or cameras.
- "shots": for each shot, "seconds" (2 to 8), "cast" (the names in it, may be empty) and "video": 2 to 4 sentences in the present tense: the shot size and angle, who or what is in frame and exactly what they do from the start to the end of the shot, the setting, the light, and how the camera moves. Use the cast names; never describe them again. Real-world physics, believable motion, one continuous action per shot. No on-screen text, titles or captions{talk}.
Answer with only a JSON object with the keys "title" (2 to 5 words), "cast", "look" and "shots"."""


def films_dir(out_root: str) -> str:
    return os.path.join(out_root, "oneshot-mv", "films")


def _slug(s: str) -> str:
    return re.sub(r"[^a-z0-9]+", "-", s.lower()).strip("-")[:40] or "film"


def _decode(path: str) -> tuple[np.ndarray, int]:
    from .assemble import ffmpeg_exe
    sr = 44100
    raw = subprocess.run([ffmpeg_exe(), "-v", "error", "-nostdin", "-i", path, "-f", "f32le", "-ac", "2", "-ar", str(sr), "-"],
                         capture_output=True, check=True).stdout
    return np.frombuffer(raw, np.float32).reshape(-1, 2).T.copy(), sr


def write_shots(script: str, seconds: float, kind: str = "film", style: str = "", seed: int = 1, log=print) -> dict:
    """{title, cast: [{name, look}], look, shots: [{seconds, cast, video}]} from Gemma."""
    from . import theme
    n = max(2, int(round(seconds / (3.2 if kind == "commercial" else 4.5))))
    want = PROMPT.format(kind={"commercial": "TV commercial", "film": "short film"}.get(kind, kind), script=script.strip(),
                         n=n, seconds=int(round(seconds)), style=f"Style: {style.strip()}." if style.strip() else "",
                         talk=", nobody talks to the camera" if kind != "film" else "")
    for attempt in range(3):
        d = theme._parse(theme.llm(want, seed=seed + attempt, max_length=2600, log=log) or "")
        shots = (d or {}).get("shots") or []
        if len(shots) >= 2 and all(isinstance(s, dict) and str(s.get("video", "")).strip() for s in shots):
            break
        log(f"[OneShotMV] film: the shot list didn't parse (try {attempt + 1})")
        d = None
    if not d:
        raise RuntimeError("Gemma couldn't write a shot list for this brief: try a longer or plainer script.")
    cast = []
    raw = d.get("cast") or []
    if isinstance(raw, dict):  # {"Silas": "a man in his seventies..."} or {"Silas": {...}}
        raw = [{"name": k, **(v if isinstance(v, dict) else {"look": v})} for k, v in raw.items()]
    for c in raw if isinstance(raw, list) else []:
        if isinstance(c, str) and ":" in c:  # "Silas: a man in his seventies..."
            c = dict(zip(("name", "look"), (x.strip() for x in c.split(":", 1))))
        if not isinstance(c, dict):
            continue
        name = str(c.get("name") or "").strip()
        if not name:
            continue
        desc = c.get("look") or c.get("description") or c.get("visual") or c.get("desc") or \
            next((v for k, v in c.items() if k != "name" and isinstance(v, str) and len(v) > 20), "")
        cast.append({"name": name, "look": str(desc).strip()})
    return {"title": re.sub(r"[^\w' &-]+", "", str(d.get("title") or "Untitled")).strip()[:60] or "Untitled",
            "cast": cast, "look": str(d.get("look") or "").strip(), "raw": d,
            "shots": [{"seconds": float(s.get("seconds") or 4), "cast": [str(x) for x in (s.get("cast") or []) if x],
                       "video": str(s["video"]).strip()} for s in d["shots"]]}


# film formats and stocks in a text-to-video prompt bring the film itself into the picture: a
# rounded gate, sprocket holes, a frame border (LTX-2.5 at cfg 1 has no negative prompt to stop it)
_FILMIC = re.compile(r"\b(?:(?:shot|captured|filmed) on )?(?:(?:super ?8|8 ?mm|16 ?mm|35 ?mm|65 ?mm|70 ?mm|imax)(?: film)?(?: stock)?|"
                     r"kodak(?: \w+)?(?: \d{2,4}\w?)?|fuji(?:film)?(?: \w+)?(?: \d{2,4})?|portra(?: \d+)?|"
                     r"cinestill(?: \d+\w?)?|ektachrome|film stock|film grain|celluloid)\b", re.I)


def defilm(text: str) -> str:
    """A look without film stocks or formats ("35mm film stock, Kodak Portra 400" -> a film look)."""
    t = _FILMIC.sub("", text or "")
    t = re.sub(r"\s*,\s*(,\s*)+", ", ", t)
    t = re.sub(r"^[\s,;:]+|[\s,;]+$", "", re.sub(r"\s{2,}", " ", t)).strip()
    return re.sub(r"\s+([,.;])", r"\1", t)


def prompt_for(film: dict, shot: dict) -> str:
    """A shot's whole prompt: its action with every named cast member described in full (the model
    sees one shot at a time), then the film's look."""
    text = shot["video"]
    who = [c for c in film.get("cast", []) if c["name"] in shot.get("cast", []) or c["name"].lower() in text.lower()]
    if who:
        lc = lambda t: t[0].lower() + t[1:] if re.match(r"(A|An|The)\b", t) else t  # "Silas is an 82-year-old man"
        text += " " + " ".join(f"{c['name']} is {lc(c['look'].rstrip('.'))}." for c in who if c["look"])
    look, style = defilm(film.get("look", "")), defilm(film.get("style", ""))
    if look:
        text += f" Look: {look.rstrip('.')}."
    if style:
        text += f" Style: {style.rstrip('.')}."
    text = defilm(text) if _FILMIC.search(text) else text
    return text + MOTION


def _timing(shots: list[dict], seconds: float, beats: list[float] | None) -> list[tuple[float, float]]:
    """(t0, t1) per shot: the written lengths scaled to the film's, each cut moved onto the nearest
    beat of the music when there is music (a shot keeps at least 1.2 s)."""
    raw = [min(8.0, max(1.5, float(s["seconds"]))) for s in shots]
    k = seconds / sum(raw)
    cuts, t = [], 0.0
    for r in raw[:-1]:
        t += r * k
        cuts.append(t)
    if beats:
        b = np.array([x for x in beats if 0.8 < x < seconds - 0.8])
        snapped, last = [], 0.0
        for c in cuts:
            if len(b):
                cand = b[(b > last + 1.2)]
                c = float(cand[np.argmin(np.abs(cand - c))]) if len(cand) else c
            snapped.append(c)
            last = c
        cuts = snapped
    edges = [0.0] + cuts + [seconds]
    return [(round(edges[i], 3), round(edges[i + 1], 3)) for i in range(len(shots))]


def _beats(song_path: str, start: float, seconds: float) -> tuple[list[float], float, float]:
    """The song's beat times inside the film's window (from 0), the window's start and the tempo."""
    from . import beat
    x, sr = _decode(song_path)
    tl = beat.analyze(x, sr)
    dur = x.shape[1] / sr
    if start < 0:  # the strongest stretch, as the music video picks it
        try:
            start = float(beat.choose_window(tl, seconds)[0])
        except Exception:
            start = 0.0
    start = max(0.0, min(start, max(0.0, dur - seconds)))
    bts = [float(b) - start for b in tl.get("beats", []) if start <= float(b) <= start + seconds]
    return bts, start, float(tl.get("tempo") or 0)


def shot_job(film: dict, i: int, seed: int, take: int = 0) -> dict:
    """One shot's text-to-video graph (a re-shoot: a new seed and a _t<take> name)."""
    s = film["shots"][i]
    fps = formats.PRESETS[film["preset"]]["fps"]
    frames = formats.ltx_frames(s["t1"] - s["t0"] + 0.2, fps)
    name = f"s{i:03d}" + (f"_t{take}" if take else "")
    g = graphs.ltx_render(vsr=bool(film.get("h3_vsr")), preset=film["preset"], fmt=film["format"], key_path=None,
                          prompt=s["prompt"], negative=NEGATIVE, frames=frames, seed=seed, prefix=f"{film['rel']}/{name}",
                          size=formats.render_size(film["format"], film["preset"]), sound=True)
    return g.nodes


def plan(*, script: str, seconds: float, fmt: str, preset: str, seed: int, out_root: str, kind: str = "film",
         style: str = "", song_path: str = "", song_start: float = -1.0, look: str = "none", run_name: str = "",
         h3_upscale: str = "auto", sound: bool = True, log=print) -> dict:
    """Write the shot list and save film.json; returns the film (its jobs under "jobs")."""
    t = time.time()
    seconds = float(max(5.0, min(300.0, seconds)))
    spec = write_shots(script, seconds, kind, style, seed, log)
    name = run_name or f"{_slug(spec['title'])}-{time.strftime('%Y%m%d-%H%M')}"
    d = os.path.join(films_dir(out_root), name)
    os.makedirs(d, exist_ok=True)
    film = {"version": 1, "kind": kind, "script": script, "style": style, "seconds": seconds, "format": fmt,
            "preset": preset, "seed": seed, "look_grade": look, "sound": bool(sound), "run": name, "dir": d,
            "rel": os.path.relpath(d, out_root).replace(os.sep, "/"), "title": spec["title"], "cast": spec["cast"],
            "look": spec["look"], "llm": spec.get("raw"), "song": song_path, "song_start": 0.0, "tempo": 0.0,
            "h3_vsr": formats.engine_of(preset) == "h3" and h3_upscale == "relayvsr" and graphs.relayvsr_ready(),
            "created": time.strftime("%Y-%m-%dT%H:%M")}
    beats = None
    if song_path:
        beats, film["song_start"], film["tempo"] = _beats(song_path, song_start, seconds)
    film["shots"] = spec["shots"]
    for s, (t0, t1) in zip(film["shots"], _timing(spec["shots"], seconds, beats)):
        s["t0"], s["t1"] = t0, t1
        s["prompt"] = prompt_for(film, s)
    film["jobs"] = [{"name": f"s{i:03d}", "shot": i, "graph": shot_job(film, i, seed * 1000 + i)}
                    for i in range(len(film["shots"]))]
    save(film)
    log(f"[OneShotMV] film: \"{film['title']}\", {len(film['shots'])} shots, {seconds:.0f} s, "
        f"{len(film['cast'])} in the cast ({time.time() - t:.0f} s)")
    return film


def save(film: dict) -> None:
    with open(os.path.join(film["dir"], "film.json"), "w", encoding="utf-8") as f:
        json.dump(film, f, indent=1)


def load(d: str) -> dict:
    with open(os.path.join(d, "film.json"), encoding="utf-8") as f:
        return json.load(f)


def cut_graph(d: str) -> dict:
    return {"1": {"class_type": "FVFilmCut", "inputs": {"film_dir": d}}}


def clip_for(d: str, i: int) -> str:
    """Shot i's newest take."""
    paths = glob.glob(os.path.join(d, f"s{i:03d}_*.mp4"))
    return max(paths, key=os.path.getmtime) if paths else ""


def _clip_audio(path: str, seconds: float, sr: int) -> np.ndarray:
    from .assemble import ffmpeg_exe
    n = int(round(seconds * sr))
    try:
        raw = subprocess.run([ffmpeg_exe(), "-v", "error", "-nostdin", "-i", path, "-t", f"{seconds:.4f}", "-f", "f32le",
                              "-ac", "2", "-ar", str(sr), "-"], capture_output=True, check=True).stdout
        a = np.frombuffer(raw, np.float32).reshape(-1, 2).T
    except Exception:
        a = np.zeros((2, 0), np.float32)
    out = np.zeros((2, n), np.float32)
    out[:, :min(n, a.shape[1])] = a[:, :n]
    fade = min(n // 2, int(0.02 * sr))  # no click at the cut
    if fade:
        ramp = np.linspace(0, 1, fade, dtype=np.float32)
        out[:, :fade] *= ramp
        out[:, n - fade:] *= ramp[::-1]
    return out


def cut(d: str, log=print) -> str:
    """final.mp4: every shot's newest take trimmed to its slot, the music or the shots' sound, the finish."""
    import torch
    from . import casting, stems
    from .assemble import ffmpeg_exe
    from .finish import STUDIO_DEFAULTS, Finisher, lab_stats
    film = load(d)
    fps = float(formats.PRESETS[film["preset"]]["fps"])
    dw, dh = formats.deliver_size(film["format"], int(film.get("resolution") or 1080))
    seconds = float(film["seconds"])
    shots = film["shots"]
    paths = [clip_for(d, i) for i in range(len(shots))]
    if not any(paths):
        raise RuntimeError("no shots rendered yet")
    dev = "cuda" if torch.cuda.is_available() else "cpu"

    def frames_of(path: str, n: int):
        """n frames of a clip from its start, covering the delivery size (black when it's missing)."""
        if not path:
            for _ in range(n):
                yield np.zeros((dh, dw, 3), np.uint8)
            return
        p = subprocess.Popen([ffmpeg_exe(), "-v", "error", "-nostdin", "-i", path, "-vf",
                              f"fps={fps},scale={dw}:{dh}:force_original_aspect_ratio=increase:flags=lanczos,crop={dw}:{dh}",
                              "-frames:v", str(n), "-f", "rawvideo", "-pix_fmt", "rgb24", "-"], stdout=subprocess.PIPE)
        last, k = None, 0
        while k < n:
            buf = p.stdout.read(dw * dh * 3)
            if len(buf) < dw * dh * 3:
                break
            last = np.frombuffer(buf, np.uint8).reshape(dh, dw, 3)
            k += 1
            yield last
        p.stdout.close()
        p.wait()
        for _ in range(n - k):  # a clip shorter than its slot holds its last frame
            yield last if last is not None else np.zeros((dh, dw, 3), np.uint8)

    # the finish: the house base and the Studio's grade, grain and vignette
    pk = casting.load_pack("crowd")
    cfg = dict(pk["finish"], **STUDIO_DEFAULTS)
    cfg.update({"look": film.get("look_grade") or "none", "grade_amount": 0.0}, **(film.get("finish_user") or {}))
    samples = []
    for p in paths:
        for f in frames_of(p, 1):
            samples.append(torch.from_numpy(f.copy()).to(dev).float() / 255)
    fin = Finisher(cfg, lab_stats(samples) if samples else None)

    # the sound: the music from its window, or every shot's own sound in its slot
    sr = 44100
    wav = os.path.join(d, "sound.wav")
    if film.get("song") and os.path.isfile(film["song"]):
        x, ssr = _decode(film["song"])
        a = x[:, int(film.get("song_start", 0) * ssr):int((film.get("song_start", 0) + seconds) * ssr)]
        n = int(seconds * ssr)
        if a.shape[1] < n:
            a = np.pad(a, ((0, 0), (0, n - a.shape[1])))
        fade = int(min(1.5, seconds / 6) * ssr)  # out, not cut off
        a[:, -fade:] *= np.linspace(1, 0, fade, dtype=np.float32)
        stems.write_wav(wav, a.astype(np.float32), ssr)
    elif film.get("sound", True):
        parts = [_clip_audio(p, s["t1"] - s["t0"], sr) if p else np.zeros((2, int((s["t1"] - s["t0"]) * sr)), np.float32)
                 for p, s in zip(paths, shots)]
        a = np.concatenate(parts, axis=1)
        peak = float(np.abs(a).max() or 1.0)  # up to -1 dBFS peak (the models' sound comes out quiet), at most +12 dB
        stems.write_wav(wav, (a * min(4.0, 0.89 / peak)).astype(np.float32), sr)
    else:
        stems.write_wav(wav, np.zeros((2, int(seconds * sr)), np.float32), sr)

    out = os.path.join(d, "final.mp4")
    tmp = out + ".part.mp4"
    enc = subprocess.Popen([ffmpeg_exe(), "-v", "error", "-y", "-f", "rawvideo", "-pix_fmt", "rgb24", "-s", f"{dw}x{dh}",
                            "-r", str(fps), "-i", "-", "-i", wav, "-map", "0:v", "-map", "1:a", "-c:v", "libx264",
                            "-crf", "16", "-preset", "medium", "-tune", "grain", "-maxrate", "40M", "-bufsize", "60M",
                            "-pix_fmt", "yuv420p", "-movflags", "+faststart", "-c:a", "aac", "-b:a", "256k", "-shortest", tmp],
                           stdin=subprocess.PIPE)
    k = 0
    thumb = None
    for i, (p, s) in enumerate(zip(paths, shots)):
        n = int(round(s["t1"] * fps)) - int(round(s["t0"] * fps))
        for f in frames_of(p, n):
            x = torch.from_numpy(f.copy()).to(dev).float() / 255
            y = (fin(x, k).clamp(0, 1) * 255).round().byte().cpu().numpy()
            if thumb is None and k >= n // 2:
                thumb = y
            enc.stdin.write(y.tobytes())
            k += 1
    enc.stdin.close()
    enc.wait()
    if enc.returncode:
        raise RuntimeError("ffmpeg failed to write the cut")
    os.replace(tmp, out)
    if thumb is not None:
        import cv2
        cv2.imwrite(os.path.join(d, "thumb.jpg"), cv2.cvtColor(thumb, cv2.COLOR_RGB2BGR)[:, :, :],
                    [cv2.IMWRITE_JPEG_QUALITY, 88])
    film["final"] = out
    film["cut_at"] = time.strftime("%Y-%m-%dT%H:%M:%S")
    save(film)
    log(f"[OneShotMV] film: cut {film['title']} ({k} frames, {sum(1 for p in paths if p)}/{len(paths)} shots)")
    return out
